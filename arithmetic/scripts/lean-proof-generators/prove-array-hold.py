#!/usr/bin/env python3
"""Generate kernel-checked output-hold lemmas from the exported array DAG.

The generated proof is the authority: parsing mistakes or a changed circuit
must fail Lean checking. No truth values or axioms are injected.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
parts = sorted((root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean'))
source = '\n'.join(p.read_text() for p in parts)
nodes = {int(n): expression for n, expression in re.findall(
    r'def v(\d+) \(s : State\) \(i : Inputs\) : BitVec \d+ := ([^\n]+)', source)}
output = int(re.search(r'output := \{nio_5Fresult := \(v(\d+) s i\)', source)[1])
cone = set()
leaves = set()
pending = [output]
while pending:
    node = pending.pop()
    if node in cone:
        continue
    cone.add(node)
    expression = nodes[node]
    if re.search(r'\bi\.\w+', expression):
        raise ValueError(f'Output depends on input pins at v{node}')
    pending.extend(map(int, re.findall(r'v(\d+) s i', expression)))
    leaves.update(re.findall(r's\.(g\d+\.r\w+)', expression))

lines = ['import Generated.ArrayMulDataModule', '',
         '-- Generated by scripts/prove-array-hold.py; checked by Lean.',
         'namespace ArrayHold', 'open nArrayMulDataModule', '',
         '/-- The actual array output holds when the second stage is disabled,',
         'for arbitrary initial registers, reset, first-stage enable, and input pins. -/',
         'theorem output_hold (s : State) (i before after : Inputs)',
         '    (disabled : i.nio_5FregEnables_5F1 = 0) :',
         '    observe (step s i) after = observe s before := by']
assignments = dict(re.findall(r"\b(r\d+_\w+) := \(v(\d+) s i\)", source))
for field in sorted(leaves):
    register = field.split('.')[1]
    node = int(assignments[register])
    if not nodes[node].startswith('if i.nio_5FregEnables_5F1 = 1 then '):
        raise ValueError(f'{field} does not have expected second-stage enable')
    lines.extend([f'  have h_{register} : (step s i).{field} = s.{field} := by',
                  f'    change v{node} s i = s.{field}',
                  f'    simp [v{node}, disabled]'])
for node in sorted(cone):
    expression = nodes[node]
    deps = sorted(set(map(int, re.findall(r'v(\d+) s i', expression))))
    fields = sorted(set(re.findall(r's\.(g\d+\.r\w+)', expression)))
    rewrites = [f'v{node}'] + [f'h{dep}' for dep in deps]
    rewrites += [f'h_{field.split(".")[1]}' for field in fields]
    lines.extend([f'  have h{node} : v{node} (step s i) after = v{node} s before := by',
                  f'    simp only [{", ".join(rewrites)}]'])
lines.extend([f'  exact congrArg Outputs.mk h{output}', '', 'end ArrayHold', ''])
(root / 'lean/Proofs/ArrayHold.lean').write_text('\n'.join(lines))
print(f'Generated hold proof: {len(leaves)} registers and {len(cone)} DAG nodes')
