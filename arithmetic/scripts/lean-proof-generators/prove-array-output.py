#!/usr/bin/env python3
"""Connect the final exported compressor to three register rows; Lean checks all identities."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
source = '\n'.join(p.read_text() for p in sorted((root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean')))
nodes = {int(n): e for n, e in re.findall(r'def v(\d+) \(s : State\) \(i : Inputs\) : BitVec \d+ := ([^\n]+)', source)}
output = int(re.search(r'output := \{nio_5Fresult := \(v(\d+) s i\)', source)[1])
m = re.fullmatch(r'\(v(\d+) s i\) \+ \(v(\d+) s i\)', nodes[output][1:-1])
assert m, 'Expected final sum and carry addition'
sum_node, carry_node = map(int, m.groups())
refs = r'\(v(\d+) s i\)|s\.(g\d+\.r\w+)'

def xor_fields(node):
    expr = nodes[node]
    assert '^^^' in expr and not re.search(r'&&&|\|\|\||\+\+|\bi\.', expr), expr
    result = []
    for dep, field in re.findall(refs, expr):
        result.extend(xor_fields(int(dep)) if dep else [field])
    return result

columns = [xor_fields(int(n)) if n else [field] for n, field in re.findall(refs, nodes[sum_node])]
assert len(columns) == 130 and max(map(len, columns)) == 3

def concat(bits):
    result = bits[0]
    for bit in bits[1:]:
        result = f'({result} ++ {bit})'
    return result

def cone(node):
    result = {node}
    for dep in re.findall(r'v(\d+) s i', nodes[node]):
        result |= cone(int(dep))
    return result

lines = ['import Generated.ArrayMulDataModule', 'import Proofs.CarrySaveWide', '',
         '-- Generated by scripts/prove-array-output.py; checked by Lean.',
         'namespace ArrayOutput', 'open nArrayMulDataModule', '',
         'set_option maxRecDepth 8192', 'set_option maxHeartbeats 2000000', '']
for k in range(3):
    bits = [f's.{column[k]}' if len(column) > k else '(0#1)' for column in columns]
    lines += [f'def row{k} (s : State) : BitVec 130 :=', f'  {concat(bits)}', '']
for label, node, rhs in [
    ('sum_word', sum_node, 'row0 s ^^^ row1 s ^^^ row2 s'),
    ('carry_word', carry_node, '(((row0 s &&& row1 s) ||| ((row0 s ^^^ row1 s) &&& row2 s)) <<< 1)')]:
    defs = ', '.join(['row0', 'row1', 'row2'] + [f'v{n}' for n in sorted(cone(node), reverse=True)])
    lines += [f'theorem {label} (s : State) (i : Inputs) :', f'    v{node} s i = {rhs} := by', f'  simp only [{defs}]', '  bv_decide', '']
lines += ['/-- The actual output is the sum of the three rows in the second register stage. -/',
          'theorem output_sum (s : State) (i : Inputs) :',
          '    (observe s i).nio_5Fresult = row0 s + row1 s + row2 s := by',
          f'  change v{output} s i = _', f'  rw [v{output}, sum_word, carry_word, CarrySaveWide.full_adder]', '',
          ]
assignments = dict(re.findall(r'\b(r\d+_\w+) := \(v(\d+) s i\)', source))
for k in range(3):
    bits = []
    next_bits = []
    next_nodes = []
    for column in columns:
        if len(column) <= k:
            bits.append('(0#1)')
            next_bits.append('(0#1)')
            continue
        field = column[k]
        node = int(assignments[field.split('.')[1]])
        match = re.fullmatch(r'if i.nio_5FregEnables_5F1 = 1 then \(v(\d+) s i\) else s\.' + re.escape(field), nodes[node])
        assert match, nodes[node]
        bits.append(f'(v{match[1]} s i)')
        next_bits.append(f'(v{node} s i)')
        next_nodes.append(node)
    lines += [f'def incomingRow{k} (s : State) (i : Inputs) : BitVec 130 :=',
              f'  {concat(bits)}', '',
              f'theorem capture_row{k} (s : State) (i : Inputs)',
              '    (enabled : i.nio_5FregEnables_5F1 = 1) :',
              f'    row{k} (step s i) = incomingRow{k} s i := by',
              f'  change ({concat(next_bits)} : BitVec 130) = incomingRow{k} s i',
              '  simp only [' + ', '.join([f'incomingRow{k}', 'enabled', 'if_true'] + [f'v{n}' for n in next_nodes]) + ']', '']
lines += ['/-- An enabled second-stage edge captures the numeric sum of its actual input rows. -/',
          'theorem output_capture (s : State) (i after : Inputs)',
          '    (enabled : i.nio_5FregEnables_5F1 = 1) :',
          '    (observe (step s i) after).nio_5Fresult =',
          '      incomingRow0 s i + incomingRow1 s i + incomingRow2 s i := by',
          '  rw [output_sum, capture_row0 s i enabled, capture_row1 s i enabled,',
          '    capture_row2 s i enabled]', '', 'end ArrayOutput', '']
(root / 'lean/Proofs/ArrayOutput.lean').write_text('\n'.join(lines))
print(f'Generated output composition for {len(columns)} columns and {sum(map(len, columns))} register bits')
