#!/usr/bin/env python3
"""Connect all actual first-stage row/correction registers to Booth nodes."""
import pathlib
import re
root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
source = '\n'.join(p.read_text() for p in sorted((root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean')))
nodes = {int(n): (int(w), e) for n, w, e in re.findall(r'def v(\d+) .*? : BitVec (\d+) := ([^\n]+)', source)}
row_source = (root / 'lean/Proofs/ArrayRows.lean').read_text()
rows = list(map(int, re.findall(r'theorem row_\d+ .*? : v(\d+)', row_source)))
corrections = list(map(int, re.findall(r'theorem correction_\d+ .*? : \(v(\d+)', row_source)))
if len(rows) != 33 or len(corrections) != 33:
    raise ValueError('Expected 33 rows and corrections')
captures = {}
for node, (_, expression) in nodes.items():
    match = re.fullmatch(r'if i.nio_5FregEnables_5F0 = 1 then \(v(\d+) s i\) else s\.(g\d+\.r\w+)', expression)
    if match:
        data = int(match[1])
        extract = re.fullmatch(r"BitVec.extractLsb' (\d+) 1 \(v(\d+) s i\)", nodes[data][1])
        if extract:
            captures[(int(extract[2]), int(extract[1]))] = (match[2], node, data)

def concat(terms):
    result = terms[0]
    for term in terms[1:]:
        result = f'({result} ++ {term})'
    return result

lines = ['import Proofs.ArrayRowSum', '', '-- Generated by scripts/prove-array-capture.py; checked by Lean.',
         'namespace ArrayCapture', 'open nArrayMulDataModule', 'set_option maxRecDepth 8192', '']
for width in [2, 66]:
    terms = [f"(p.extractLsb' {j} 1)" for j in reversed(range(width))]
    lines += [f'private theorem reassemble{width} (p : BitVec {width}) : {concat(terms)} = p := by bv_decide', '']
for kind, width, selected in [('row', 66, rows), ('correction', 2, corrections)]:
    for k, node in enumerate(selected):
        bits = [captures[(node, j)] for j in reversed(range(width))]
        fields = concat([f's.{field}' for field, _, _ in bits])
        next_nodes = concat([f'(v{n} s i)' for _, n, _ in bits])
        unfold = sorted({n for _, n, _ in bits} | {d for _, _, d in bits}, reverse=True)
        lines += [f'def registered_{kind}_{k} (s : State) : BitVec {width} := {fields}',
                  f'theorem capture_{kind}_{k} (s : State) (i : Inputs) (enabled : i.nio_5FregEnables_5F0 = 1) :',
                  f'    registered_{kind}_{k} (step s i) = v{node} s i := by',
                  f'  change {next_nodes} = v{node} s i',
                  '  simp only [' + ', '.join([f'v{n}' for n in unfold] + ['enabled', 'if_true']) + ']',
                  f'  exact reassemble{width} _', '',
                  f'theorem hold_{kind}_{k} (s : State) (i : Inputs) (disabled : i.nio_5FregEnables_5F0 = 0) :',
                  f'    registered_{kind}_{k} (step s i) = registered_{kind}_{k} s := by',
                  f'  change {next_nodes} = {fields}',
                  '  simp only [' + ', '.join([f'v{n}' for _, n, _ in bits] + ['disabled', 'show (0 : BitVec 1) ≠ 1 from by decide', 'if_false']) + ']', '']
expression = '0'
for k in reversed(range(33)):
    expression = f'((registered_row_{k} s).signExtend 130 + (registered_correction_{k} s).zeroExtend 130) + 4 * ({expression})'
lines += [f'def registeredRowSum (s : State) : BitVec 130 := {expression}', '',
          '/-- A first-stage capture establishes the signed product in the',
          'weighted sum of actual row and correction registers. -/',
          'theorem capture_product (s : State) (i : Inputs) (enabled : i.nio_5FregEnables_5F0 = 1) :',
          '    registeredRowSum (step s i) = BitVec.ofInt 130 (i.nio_5Fa.toInt * i.nio_5Fb.toInt) := by',
          '  simp only [' + ', '.join(['registeredRowSum'] + [f'capture_{kind}_{k} s i enabled' for kind in ['row', 'correction'] for k in range(33)]) + ']',
          '  exact ArrayRows.corrected_row_sum s i', '',
          'theorem hold_sum (s : State) (i : Inputs) (disabled : i.nio_5FregEnables_5F0 = 0) :',
          '    registeredRowSum (step s i) = registeredRowSum s := by',
          '  simp only [' + ', '.join(['registeredRowSum'] + [f'hold_{kind}_{k} s i disabled' for kind in ['row', 'correction'] for k in range(33)]) + ']',
          '', 'end ArrayCapture', '']
(root / 'lean/Proofs/ArrayCapture.lean').write_text('\n'.join(lines))
print('Generated first-stage capture proofs for all 33 row/correction pairs')
