#!/usr/bin/env python3
"""Connect the exported 65-bit array's Booth nodes to checked definitions."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
source = '\n'.join(p.read_text() for p in sorted(
    (root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean')))
nodes = {int(n): (int(w), e) for n, w, e in re.findall(
    r'def v(\d+) .*? : BitVec (\d+) := ([^\n]+)', source)}
rows, corrections = set(), set()
for _, expression in nodes.values():
    if not expression.startswith('if i.nio_5FregEnables_5F0 = 1 then'):
        continue
    dep = int(re.search(r'then \(v(\d+) s i\)', expression)[1])
    extract = re.fullmatch(r"BitVec.extractLsb' \d+ 1 \(v(\d+) s i\)", nodes[dep][1])
    if extract:
        node = int(extract[1])
        if nodes[node][0] == 66:
            rows.add(node)
        elif nodes[node][0] == 2:
            corrections.add(node)
if len(rows) != 33 or len(corrections) != 33:
    raise ValueError('Expected exactly 33 Booth rows and corrections')
lines = ['import Generated.ArrayMulDataModule', 'import Proofs.BoothPadding', '',
         '-- Generated by scripts/prove-array-rows.py; checked by Lean.',
         'namespace ArrayRows', 'open nArrayMulDataModule', '']
for k, (row, correction) in enumerate(zip(sorted(rows), sorted(corrections))):
    window = "(i.nio_5Fa.extractLsb' 0 2 ++ 0#1)" if k == 0 else (
        "((i.nio_5Fa.extractLsb' 63 2).signExtend 3)" if k == 32 else
        f"(i.nio_5Fa.extractLsb' {2*k-1} 3)")
    for node, kind in [(row, 'row'), (correction, 'correction')]:
        cone = set()
        def visit(n):
            if n in cone:
                return
            cone.add(n)
            if 's.g' in nodes[n][1]:
                raise ValueError('Booth selector unexpectedly depends on registers')
            for dep in map(int, re.findall(r'v(\d+) s i', nodes[n][1])):
                visit(dep)
        visit(node)
        lhs = f'v{node} s i' if kind == 'row' else f'(v{node} s i).zeroExtend 66'
        rhs = f'BoothRecoding.row (i.nio_5Fb.signExtend 66) {window}' if kind == 'row' else f'BoothRecoding.correction {window}'
        lines += [f'theorem {kind}_{k} (s : State) (i : Inputs) : {lhs} = {rhs} := by',
                  '  simp only [' + ', '.join([f'v{n}' for n in sorted(cone, reverse=True)] + [f'BoothRecoding.{kind}']) + ']',
                  '  bv_decide', '']
lines += ['end ArrayRows', '']
target = root / 'lean/Proofs/ArrayRows.lean'
text = '\n'.join(lines)
if not target.exists() or target.read_text() != text:
    target.write_text(text)
print('Generated 33 row and 33 correction proofs')

lines = ['import Proofs.ArrayRows', 'import Proofs.BoothWide', '',
         '-- Generated by scripts/prove-array-rows.py; checked by Lean.',
         'namespace ArrayRows', 'open nArrayMulDataModule', '',
         'private theorem widen_correction (x : BitVec 2) :',
         '    (x.zeroExtend 66).zeroExtend 130 = x.zeroExtend 130 := by bv_decide', '']
for k, (row, correction) in enumerate(zip(sorted(rows), sorted(corrections))):
    window = "(i.nio_5Fa.extractLsb' 0 2 ++ 0#1)" if k == 0 else (
        "((i.nio_5Fa.extractLsb' 63 2).signExtend 3)" if k == 32 else
        f"(i.nio_5Fa.extractLsb' {2*k-1} 3)")
    lines += [f'theorem wide_row_{k} (s : State) (i : Inputs) :',
              f'    (v{row} s i).signExtend 130 + (v{correction} s i).zeroExtend 130 =',
              f'      i.nio_5Fb.signExtend 130 * BitVec.ofInt 130',
              f'        (BoothRecoding.digit ({window}.getLsbD 0) ({window}.getLsbD 1, {window}.getLsbD 2)) := by',
              f'  have correction := congrArg (fun x : BitVec 66 => x.zeroExtend 130) (correction_{k} s i)',
              '  dsimp only at correction',
              '  rw [widen_correction] at correction',
              f'  rw [row_{k}, correction]',
              f'  exact BoothRecoding.corrected_row_wide_window i.nio_5Fb {window}', '']
lines += ['end ArrayRows', '']
(root / 'lean/Proofs/ArrayWideRows.lean').write_text('\n'.join(lines))

lines = ['import Proofs.ArrayWideRows', 'import Proofs.BoothOperand', '',
         '-- Generated by scripts/prove-array-rows.py; checked by Lean.',
         'namespace ArrayRows', 'open nArrayMulDataModule', '']
expression = '0'
for row, correction in reversed(list(zip(sorted(rows), sorted(corrections)))):
    expression = f'((v{row} s i).signExtend 130 + (v{correction} s i).zeroExtend 130) + 4 * ({expression})'
header = [f'def correctedRowSum (s : State) (i : Inputs) : BitVec 130 := {expression}', '',
          '/-- The weighted sum of all actual raw rows and correction nodes is',
          'the signed product. Register packing and compression are separate. -/',
          'theorem corrected_row_sum (s : State) (i : Inputs) :',
          '    correctedRowSum s i = BitVec.ofInt 130 (i.nio_5Fa.toInt * i.nio_5Fb.toInt) := by']
bitLines = []
proofLines = []
for k in range(33):
    window = "(i.nio_5Fa.extractLsb' 0 2 ++ 0#1)" if k == 0 else (
        "((i.nio_5Fa.extractLsb' 63 2).signExtend 3)" if k == 32 else
        f"(i.nio_5Fa.extractLsb' {2*k-1} 3)")
    shifted = f'((i.nio_5Fa.signExtend 66).sshiftRight {2*k})'
    previous = 'false' if k == 0 else f'(((i.nio_5Fa.signExtend 66).sshiftRight {2*k-2}).getLsbD 1)'
    bitLines += [f'theorem bits_{k} (s : State) (i : Inputs) : ({window}.getLsbD 0, ({window}.getLsbD 1, {window}.getLsbD 2)) =',
              f'      ({previous}, ({shifted}.getLsbD 0, {shifted}.getLsbD 1)) := by',
              '  simp only [Prod.mk.injEq]', '  bv_decide', '']
    proofLines += [f'  have digit{k} := congrArg (fun p : Bool × (Bool × Bool) => BoothRecoding.digit p.1 p.2) (bits_{k} s i)',
              f'  dsimp only at digit{k}']
lines += bitLines + header + proofLines
lines += ['  rw [← BoothRecoding.wide_operand_product]',
          '  simp only [BoothRecoding.operandPairs, BoothRecoding.wideProducts,',
          '    ← BitVec.sshiftRight_add, Nat.reduceAdd]',
          '  simp only [' + ', '.join(['correctedRowSum'] + [f'wide_row_{k}' for k in range(33)] + [f'digit{k}' for k in range(33)] + ['BitVec.sshiftRight_zero']) + ']',
          '', 'end ArrayRows', '']
(root / 'lean/Proofs/ArrayRowSum.lean').write_text('\n'.join(lines))

pairs = [f'(v{row} s i, v{correction} s i)' for row, correction in zip(sorted(rows), sorted(corrections))]
lines = ['import Proofs.ArrayRowSum', 'import Proofs.BoothPackedSum', '',
         '-- Generated by scripts/prove-array-rows.py; checked by Lean.',
         'namespace ArrayRows', 'open nArrayMulDataModule',
         'set_option maxRecDepth 4096', '',
         'def packedRowSum (s : State) (i : Inputs) : BitVec 130 :=',
         f'  (BoothRecoding.firstPadded (v{min(rows)} s i)).zeroExtend 130 +',
         f'    BoothRecoding.packedTail (v{min(corrections)} s i) [{", ".join(pairs[1:])}]', '',
         '/-- The Chisel sign-padding and delayed-correction layout preserves',
         'the signed product for the actual exported row-selector nodes. -/',
         'theorem packed_row_sum (s : State) (i : Inputs) :',
         '    packedRowSum s i = BitVec.ofInt 130 (i.nio_5Fa.toInt * i.nio_5Fb.toInt) := by',
         '  calc',
         '    packedRowSum s i = correctedRowSum s i := by',
         f'      exact BoothRecoding.packed_sum_65 {pairs[0]} [{", ".join(pairs[1:])}] (by rfl)',
         '    _ = _ := corrected_row_sum s i', '', 'end ArrayRows', '']
(root / 'lean/Proofs/ArrayPackedRows.lean').write_text('\n'.join(lines))
