#!/usr/bin/env python3
"""Emit Lean proofs for the actual array's local compressor assertions.

The DAG parser identifies cut points; Lean checks each resulting equality.
No parser result is trusted as a proof, axiom, or assumed arithmetic fact.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
source = '\n'.join(p.read_text() for p in sorted(
    (root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean')))
nodes = {int(n): (int(w), e) for n, w, e in re.findall(
    r'def v(\d+) \(s : State\) \(i : Inputs\) : BitVec (\d+) := ([^\n]+)', source)}
chunks = re.findall(r'def assertionChecks\d+ .*? := (\[[^\n]+)', source)
checks = [tuple(map(int, pair)) for chunk in chunks for pair in re.findall(
    r'decide \(\(v(\d+) s i\) ≠ 1 ∨ \(v(\d+) s i\) = 1\)', chunk)]
# The last two checks are the product pipeline and output hold contracts.
local = checks[:-2]
out = root / 'lean/Proofs/ArrayCompressors'
out.mkdir(exist_ok=True)
for batch in range((len(local) + 63) // 64):
    lines = ['import Generated.ArrayMulDataModule', '',
             '-- Generated by scripts/prove-array-compressors.py; checked by Lean.',
             'namespace ArrayCompressors', 'open nArrayMulDataModule', '', 'set_option maxRecDepth 4096', '']
    for _, check in local[batch * 64:(batch + 1) * 64]:
        match = re.fullmatch(r'if \(v(\d+) s i\) = \(v(\d+) s i\) then 1 else 0', nodes[check][1])
        if not match:
            raise ValueError(f'Unexpected compressor check v{check}')
        lhs, rhs = map(int, match.groups())
        expand, frontier = {check}, set()
        def left(n):
            width, expression = nodes[n]
            if width == 1 and not expression.startswith('BitVec.ofNat'):
                frontier.add(n)
                return
            expand.add(n)
            for dep in map(int, re.findall(r'v(\d+) s i', expression)):
                left(dep)
        left(lhs)
        def right(n):
            if n in frontier or n in expand:
                return
            expand.add(n)
            if len(expand) > 100:
                raise ValueError(f'Local cone exceeded limit at v{check}')
            for dep in map(int, re.findall(r'v(\d+) s i', nodes[n][1])):
                right(dep)
        right(rhs)
        def expression(n):
            if n not in expand:
                return f'(v{n} s i)'
            return '(' + re.sub(r'\(v(\d+) s i\)', lambda m: expression(int(m[1])), nodes[n][1]) + ')'
        expanded = expression(check)
        terms = list(dict.fromkeys(re.findall(r'\(v\d+ s i\)|s\.g\d+\.r\w+', expanded)))
        abstract = expanded
        for index, term in enumerate(terms):
            abstract = abstract.replace(term, f'cut{index}')
        binders = ' '.join(f'(cut{index} : BitVec 1)' for index in range(len(terms)))
        lines += [f'theorem check_{check} (s : State) (i : Inputs) : v{check} s i = 1 := by',
                  f'  have localCorrect {binders} : ({abstract} : BitVec 1) = 1 := by bv_decide',
                  '  exact localCorrect ' + ' '.join(f'({term})' for term in terms), '']
    lines += ['end ArrayCompressors', '']
    target = out / f'Part{batch:03}.lean'
    text = '\n'.join(lines)
    if not target.exists() or target.read_text() != text:
        target.write_text(text)
print(f'Generated {len(local)} compressor proofs in {batch + 1} modules')

lines = [f'import Proofs.ArrayCompressors.Part{b:03}' for b in range(batch + 1)]
lines += ['', '-- Generated by scripts/prove-array-compressors.py; checked by Lean.',
          'namespace ArrayCompressors', 'open nArrayMulDataModule',
          'set_option maxRecDepth 20000', 'set_option maxHeartbeats 4000000', '']
for k, chunk in enumerate(chunks):
    terms = re.findall(r'decide \(\(v\d+ s i\) ≠ 1 ∨ \(v\d+ s i\) = 1\)', chunk)
    count = min(len(terms), max(0, len(local) - k * 32))
    rhs = '[' + ', '.join(['true'] * count + terms[count:]) + ']'
    names = [f'check_{check}' for _, check in local[k * 32:k * 32 + count]]
    lines += [f'theorem chunk_{k} (s : State) (i : Inputs) : assertionChecks{k} s i = {rhs} := by',
              '  simp [' + ', '.join([f'assertionChecks{k}'] + names) + ']', '']
lines += ['/-- Every local compressor assertion in the exported array holds for',
          'arbitrary registers and inputs; the two top-level contracts are separate. -/',
          'theorem all_compressor_assertions (s : State) (i : Inputs) :',
          f'    ((assertionChecks s i).take {len(local)}).all id = true := by',
          '  simp only [' + ', '.join(['assertionChecks'] + [f'chunk_{k}' for k in range(len(chunks))]) + ']',
          '  rfl', '', 'end ArrayCompressors', '']
(root / 'lean/Proofs/ArrayCompressors.lean').write_text('\n'.join(lines))
