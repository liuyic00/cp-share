#!/usr/bin/env python3
"""Prove the actual first-stage sign padding and duplicate-bit relations."""
import pathlib
import re
root = pathlib.Path(__file__).resolve().parents[2] / 'verification'
source = '\n'.join(p.read_text() for p in sorted((root / 'lean/Generated/ArrayMulDataModule').glob('Part*.lean')))
nodes = {int(n): (int(w), e) for n, w, e in re.findall(r'def v(\d+) .*? : BitVec (\d+) := ([^\n]+)', source)}
registers = []
canonical = {}
for node, (width, expression) in nodes.items():
    match = re.fullmatch(r'if i.nio_5FregEnables_5F0 = 1 then \(v(\d+) s i\) else s\.(g\d+\.r\w+)', expression)
    if match and width == 1:
        data = int(match[1])
        registers.append((match[2], node, data))
        extract = re.fullmatch(r"BitVec.extractLsb' (\d+) 1 \(v(\d+) s i\)", nodes[data][1])
        if extract:
            canonical[(int(extract[2]), int(extract[1]))] = (match[2], node, data)
relations = []
for field, node, data in registers:
    expression = nodes[data][1]
    extract = re.fullmatch(r"BitVec.extractLsb' (\d+) 1 \(v(\d+) s i\)", expression)
    if extract:
        other = canonical[(int(extract[2]), int(extract[1]))]
        if field != other[0]:
            relations.append((field, node, data, other, False, []))
        continue
    xor = re.fullmatch(r'\(\(v(\d+) s i\) \^\^\^ \(v(\d+) s i\)\)', expression)
    if not xor:
        raise ValueError(f'Unexpected first-stage padding expression {expression}')
    sign, one = map(int, xor.groups())
    if nodes[one] != (1, 'BitVec.ofNat 1 1'):
        raise ValueError('Expected inversion by one')
    extract = re.fullmatch(r"BitVec.extractLsb' 65 1 \(v(\d+) s i\)", nodes[sign][1])
    if not extract:
        raise ValueError('Expected sign bit of a Booth row')
    relations.append((field, node, data, canonical[(int(extract[1]), 65)], True, [sign, one]))
if len(relations) != 34:
    raise ValueError('Expected 32 inverted sign bits and two duplicate sign bits')
conditions = [f's.{field} = ' + ('~~~' if inverted else '') + f's.{other[0]}'
              for field, _, _, other, inverted, _ in relations]
lines = ['import Proofs.ArrayFirstInvariant', '', '-- Generated by scripts/prove-array-padding.py; checked by Lean.',
         'namespace ArrayCapture', 'open nArrayMulDataModule', 'set_option maxRecDepth 8192', '',
         'private theorem invert (x : BitVec 1) : x ^^^ 1 = ~~~x := by bv_decide', '',
         'def PaddingInvariant (s : State) : Prop :=', '  ' + ' ∧\n  '.join(conditions + ['True']), '']
for k, (field, node, data, other, inverted, extra) in enumerate(relations):
    rhs = ('~~~' if inverted else '') + f'(v{other[1]} s i)'
    unfold = sorted(set([node, data, other[1], other[2]] + extra), reverse=True)
    lines += [f'theorem padding_capture_{k} (s : State) (i : Inputs) (enabled : i.nio_5FregEnables_5F0 = 1) :',
              f'    (step s i).{field} = ' + ('~~~' if inverted else '') + f'(step s i).{other[0]} := by',
              f'  change v{node} s i = {rhs}',
              '  simp only [' + ', '.join([f'v{n}' for n in unfold] + ['enabled', 'if_true']) + ']']
    if inverted:
        lines += ['  exact invert _']
    lines += ['']
lines += ['theorem padding_capture (s : State) (i : Inputs) (enabled : i.nio_5FregEnables_5F0 = 1) :',
          '    PaddingInvariant (step s i) := by',
          '  exact ⟨' + ', '.join([f'padding_capture_{k} s i enabled' for k in range(len(relations))] + ['True.intro']) + '⟩', '',
          'theorem padding_hold (s : State) (i : Inputs) (disabled : i.nio_5FregEnables_5F0 = 0) :',
          '    PaddingInvariant (step s i) ↔ PaddingInvariant s := by']
next_conditions = [f'(v{node} s i) = ' + ('~~~' if inverted else '') + f'(v{other[1]} s i)'
                   for _, node, _, other, inverted, _ in relations]
lines += ['  change (' + ' ∧ '.join(next_conditions + ['True']) + ') ↔ PaddingInvariant s',
          '  simp only [' + ', '.join(['PaddingInvariant'] + [f'v{n}' for n in sorted({n for _, n, _, _, _, _ in relations} | {o[1] for _, _, _, o, _, _ in relations})] + ['disabled', 'show (0 : BitVec 1) ≠ 1 from by decide', 'if_false']) + ']', '',
          'end ArrayCapture', '']
(root / 'lean/Proofs/ArrayPaddingRegisters.lean').write_text('\n'.join(lines))
print('Generated 34 padding-register relation proofs')
